 'use strict';
const routes = [];
const add = (method, path, handler, access = 'owner') => routes.push({ method, path, handler: `gallery.${handler}`, config: { auth: false, policies: access === 'public' ? [] : [{ name: 'global::gallery-auth', config: { review: access === 'review' } }] } });
add('GET', '/gallery/me', 'me');
add('GET', '/gallery/profile/me', 'profile');
add('PUT', '/gallery/profile/me', 'saveProfile');
add('POST', '/gallery/profile/avatar', 'avatar');
add('POST', '/gallery/profile/banner', 'banner');
add('GET', '/gallery/creators/:handle', 'portfolio', 'public');
add('GET', '/gallery/assets/:key', 'asset', 'public');
add('GET', '/gallery/works/:key/preview', 'preview', 'public');
add('GET', '/gallery/submissions', 'list');
add('POST', '/gallery/submissions', 'create');
add('GET', '/gallery/submissions/:id', 'detail');
add('PATCH', '/gallery/submissions/:id', 'update');
add('DELETE', '/gallery/submissions/:id', 'remove');
add('POST', '/gallery/submissions/:id/assets', 'upload');
add('DELETE', '/gallery/submissions/:id/assets/:assetId', 'removeAsset');
add('POST', '/gallery/submissions/:id/submit', 'submit');
add('POST', '/gallery/submissions/:id/withdraw', 'withdraw');
add('POST', '/gallery/works/:id/revisions', 'newRevision');
add('GET', '/admin/gallery/submissions', 'list', 'review');
add('GET', '/admin/gallery/submissions/:id', 'detail', 'review');
add('POST', '/admin/gallery/submissions/:id/review', 'review', 'review');
add('POST', '/admin/gallery/works/:id/unpublish', 'unpublish', 'review');
add('POST', '/admin/gallery/works/:id/republish', 'republish', 'review');
module.exports = { routes };
